-- It is READ-ONLY: one SELECT over Postgres's own catalogue. It reads no customer row and changes nothing.
-- The result is a single cell of text: the table STRUCTURE only (no data). Copy that cell and run it in the QA project.
with t as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
), parts(ord, sub, sql) as (
  select 0, '', 'set check_function_bodies = off;'
  union all
  select 1, e.extname, format('create schema if not exists %I; create extension if not exists %I with schema %I;', n.nspname, e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname in ('pgcrypto','uuid-ossp','pg_trgm','citext','vector','unaccent','btree_gin','btree_gist','fuzzystrmatch')
  union all
  select 2, ty.typname, format('create type public.%I as enum (%s);', ty.typname, (select string_agg(quote_literal(en.enumlabel), ', ' order by en.enumsortorder) from pg_enum en where en.enumtypid = ty.oid))
  from pg_type ty join pg_namespace n on n.oid = ty.typnamespace where n.nspname = 'public' and ty.typtype = 'e'
  union all
  select 3, c.relname, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S' and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
  union all
  select 4, p.proname || p.oid::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select 5, t.relname, format(E'create table public.%I (\n%s\n);', t.relname, (
    select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end, ''), E',\n' order by a.attnum)
    from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped)) from t
  union all
  select case when k.contype = 'f' then 7 else 6 end, t.relname || k.conname, format('alter table public.%I add constraint %I %s;', t.relname, k.conname, pg_get_constraintdef(k.oid))
  from pg_constraint k join t on t.oid = k.conrelid where k.contype in ('p','u','c','f','x')
  union all
  select 8, i.relname, pg_get_indexdef(x.indexrelid) || ';'
  from pg_index x join t on t.oid = x.indrelid join pg_class i on i.oid = x.indexrelid
  where not exists (select 1 from pg_constraint k where k.conindid = x.indexrelid)
  union all
  select 9, s.relname, format('alter sequence public.%I owned by public.%I.%I;', s.relname, t.relname, a.attname)
  from pg_class s join pg_depend d on d.objid = s.oid and d.deptype = 'a' join t on t.oid = d.refobjid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where s.relkind = 'S'
  union all
  select 10, v.relname, format(E'create or replace view public.%I as\n%s', v.relname, pg_get_viewdef(v.oid, true))
  from pg_class v join pg_namespace n on n.oid = v.relnamespace where n.nspname = 'public' and v.relkind = 'v'
    and not exists (select 1 from pg_depend d where d.objid = v.oid and d.deptype = 'e')
  union all
  select 11, g.tgname, pg_get_triggerdef(g.oid) || ';' from pg_trigger g join t on t.oid = g.tgrelid where not g.tgisinternal
  union all
  -- QA is locked down further than it needs to be: no table is readable with the public (anon) key.
  select 12, t.relname, format('alter table public.%I enable row level security;', t.relname) from t
)
select string_agg(sql, E'\n' order by ord, sub) as "copy this whole cell into the QA project" from parts;
